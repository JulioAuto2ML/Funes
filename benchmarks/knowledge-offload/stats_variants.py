#!/usr/bin/env python3
"""Reading table for the default-prompt variants (notebook "step 2 of the 9B plan").

  python3 stats_variants.py [--results DIR] [--out results/VARIANTS_TABLE.md] [--resamples 10000]

Per cell (model x variant, condition `tool`, 1000 unambiguous items, one greedy repeat): lookup rate with a question-bootstrap
95% CI, `contains` accuracy with CI, accuracy split by looked-up / not (n), completion-token mean and max, empty answers, the
share of answers whose summed completion tokens reach MAX_TOKENS (a proxy: truncation per call is not recorded, and tool-call
tokens count), and the paired per-question agreement of the lookup decision with the baseline `tool` default cell of the same
model. Reading aids, no p-values, outside Holm. A missing cell prints "missing", never a number.
"""
import argparse
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import verify_variants as V                                                  # noqa: E402
from ko.conditions import MAX_TOKENS                                         # noqa: E402

NB = 10000
LIMIT_FLAG = 0.02


def _load(results: Path, tag: str, var: str):
    import json
    name = f"popqa-stratified1u-n{V.N}-{tag}-tool-{var}-r0.json" if var != "default" else f"popqa-stratified1u-n{V.N}-{tag}-tool-r0.json"
    p = results / name
    if not p.exists():
        return None, name
    r = json.loads(p.read_text())
    rows = sorted([a for a in r["answers"] if a["pass"] == 1], key=lambda a: a["id"])
    return rows, name


def _ci(x, nb, seed=0):
    idx = np.random.default_rng(seed).integers(0, len(x), size=(nb, len(x)))
    m = x[idx].mean(axis=1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def analyse(results: Path, nb: int = NB) -> dict:
    out = {}
    for tag in V.TAGS:
        base_rows, _ = _load(results, tag, "default")
        base = {a["id"]: bool(a["tools"]) for a in base_rows} if base_rows else None
        for var in V.VARIANTS:
            rows, name = _load(results, tag, var)
            if rows is None:
                out[(tag, var)] = {"missing": True, "file": name}
                continue
            lk = np.array([bool(a["tools"]) for a in rows])
            ok = np.array([int(a["contains"]) for a in rows], float)
            ct = np.array([a["usage"]["completion_tokens"] for a in rows], float)
            r = {"missing": False, "file": name, "n": len(rows), "lookup": float(lk.mean()), "lookup_ci": _ci(lk.astype(float), nb),
                 "acc": float(ok.mean()), "acc_ci": _ci(ok, nb), "n_looked": int(lk.sum()), "n_not": int((~lk).sum()),
                 "acc_looked": float(ok[lk].mean()) if lk.any() else None, "acc_not": float(ok[~lk].mean()) if (~lk).any() else None,
                 "ct_mean": float(ct.mean()), "ct_max": float(ct.max()),
                 "empty": int(sum(1 for a in rows if not str(a.get("prediction", "")).strip())),
                 "limit_share": float((ct >= MAX_TOKENS).mean())}
            r["limit_flag"] = r["limit_share"] > LIMIT_FLAG
            if base is not None:
                same = [bool(a["tools"]) == base[a["id"]] for a in rows if a["id"] in base]
                r["agree_with_base"] = sum(same) / len(same) if same else None
                r["base_lookup"] = float(np.mean([base[a["id"]] for a in rows if a["id"] in base])) if same else None
            else:
                r["agree_with_base"] = None
                r["base_lookup"] = None
            out[(tag, var)] = r
    return out


def readings() -> str:
    """R1..R5 exactly as written in the notebook entry, not reworded."""
    t = (HERE / "NOTEBOOK.md").read_text()
    for line in t.splitlines():
        if "R1:" in line and "R5:" in line:
            return line[line.index("R1:"):].strip()
    return "(the readings R1-R5 were not found in NOTEBOOK.md)"


def _f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def render(results: Path, nb: int = NB) -> list:
    res = analyse(results, nb)
    L = ["# Default-prompt variants, condition `tool`, stages A and B", "",
         f"Generated by `stats_variants.py`. {nb} bootstrap resamples over questions. Baseline = the `tool` default cell of the same model "
         "(committed, not re-run). Reading aids: no p-values, outside Holm, one greedy repeat.", "",
         "| model | variant | lookup [CI] | baseline lookup | agree with baseline | acc `contains` [CI] | acc if looked up (n) | acc if not (n) "
         "| completion tokens mean / max | empty | at the limit | file |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for (tag, var), r in res.items():
        if r["missing"]:
            L.append(f"| {tag} | {var} | missing | | | | | | | | | `{r['file']}` |")
            continue
        flag = f"{r['limit_share']:.3f}" + (" **FLAG >2%**" if r["limit_flag"] else "")
        L.append(f"| {tag} | {var} | {_f(r['lookup'])} [{_f(r['lookup_ci'][0])}, {_f(r['lookup_ci'][1])}] | {_f(r['base_lookup'])} | "
                 f"{_f(r['agree_with_base'])} | {_f(r['acc'])} [{_f(r['acc_ci'][0])}, {_f(r['acc_ci'][1])}] | "
                 f"{_f(r['acc_looked'])} ({r['n_looked']}) | {_f(r['acc_not'])} ({r['n_not']}) | {r['ct_mean']:.1f} / {r['ct_max']:.0f} | "
                 f"{r['empty']} | {flag} | `{r['file']}` |")
    L += ["", f"\"At the limit\" is the share of answers whose summed completion tokens reach {MAX_TOKENS}; it is a proxy (per-call truncation is "
          "not recorded and tool-call tokens count). For `tool_free` answers will be longer by design.", "",
          "## Readings fixed before the data (copied from the notebook entry, not interpreted)", "", readings(), ""]
    return L


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default=str(HERE / "results"))
    ap.add_argument("--out", default=str(HERE / "results" / "VARIANTS_TABLE.md"))
    ap.add_argument("--resamples", type=int, default=NB)
    a = ap.parse_args()
    text = "\n".join(render(Path(a.results), a.resamples))
    Path(a.out).write_text(text + "\n")
    print(text)


if __name__ == "__main__":
    main()
