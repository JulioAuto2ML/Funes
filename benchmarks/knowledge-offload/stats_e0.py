#!/usr/bin/env python3
"""E0 results table: per-condition accuracy with CIs, paired comparisons, buckets.

Reads results/popqa-n1000-<tag>-<cell>-r<k>.json (no model, no network) and writes
results/E0_TABLE.md. Repeats are pooled by taking r0 for the deterministic harness
conditions (r0..r2 are bit-identical, see NOTEBOOK); funes varies, so repeats are averaged per question.
"""
import json, math, random, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run as runner
from ko import popqa

HERE = Path(__file__).resolve().parent
TAG = "qwen3.8-9b-q8"
CELLS = [  # (label, file stem, pass)
    ("closed", "closed", 1), ("oracle", "oracle", 1), ("store", "store", 1),
    ("tool", "tool", 1), ("tool+contract", "toolpluscontract", 1),
    ("tool/search_first", "tool-search_first", 1), ("funes@3000", "funes", 1),
    ("web/search_first", "web-search_first", 1),
    ("web+cache/search_first p1", "webpluscache-search_first", 1),
    ("web+cache/search_first p2", "webpluscache-search_first", 2),
]
PAIRS = [
    ("store", "closed"), ("oracle", "closed"), ("tool+contract", "closed"), ("tool/search_first", "closed"),
    ("tool", "closed"), ("funes@3000", "closed"), ("web/search_first", "closed"),
    ("tool+contract", "store"), ("tool/search_first", "store"), ("tool/search_first", "tool+contract"),
    ("tool+contract", "tool"), ("funes@3000", "store"), ("web/search_first", "store"),
    ("web/search_first", "tool/search_first"), ("web+cache/search_first p1", "web/search_first"),
    ("web+cache/search_first p2", "web+cache/search_first p1"), ("web+cache/search_first p2", "web/search_first"),
    ("web+cache/search_first p2", "store"),
]
_items = popqa.load(popqa.DEFAULT_PATH)
CAND, BY_ID = popqa.candidate_sets(_items), {i.id: i for i in _items}
BUCKETS = ["1e1", "1e2", "1e3", "1e4", "1e5", "1e6"]


def load(stem, pas):
    f = sorted((HERE / "results").glob(f"popqa-n1000-{TAG}-{stem}-r*.json"))
    f = [x for x in f if "smoke" not in x.name]
    if not f:
        sys.exit(f"missing cells for {stem}")
    reps = []
    for x in f:
        r = json.load(open(x))
        runner.with_hedge(r, CAND, BY_ID)  # cells from before the flag get it computed
        rows = {a["id"]: a for a in r["answers"] if a["pass"] == pas}
        reps.append(rows)
    return reps


def score(a, hedge_adj=False):
    return int(a["contains"] and not (hedge_adj and a.get("hedge")))


def ci(xs, seed=0, n=2000):
    rnd = random.Random(seed)
    m = len(xs)
    bs = sorted(sum(xs[rnd.randrange(m)] for _ in range(m)) / m for _ in range(n))
    return bs[int(.025 * n)], bs[int(.975 * n) - 1]


def mcnemar(b, c):
    n = b + c
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(n, k) for k in range(min(b, c) + 1)) / 2 ** n)


def main():
    data = {l: load(s, p) for l, s, p in CELLS}
    ids = sorted(data["closed"][0])
    pooled = {l: [sum(score(r[i]) for r in reps) / len(reps) for i in ids] for l, reps in data.items()}
    adj = {l: [sum(score(r[i], True) for r in reps) / len(reps) for i in ids] for l, reps in data.items()}
    out = ["# E0 results — %s, PopQA n=1000 (dataset seed 0), `contains` scoring" % TAG, "",
           "Generated by `stats_e0.py`. Closed/oracle/store/tool/tool+contract: 3 repeats, identical for the greedy conditions, averaged;",
           "funes@3000: mean of 3 repeats; search_first and web cells: 1 repeat. CIs: percentile bootstrap over questions (2000).", "",
           "## Accuracy", "", "| condition | reps | acc | 95% CI | acc, hedge-adj | lost to hedging |", "|---|---|---|---|---|---|"]
    for l, _, _ in CELLS:
        x, h = pooled[l], adj[l]
        lo, hi = ci(x)
        hr = (sum(x) - sum(h)) / len(x)
        out.append("| %s | %d | %.3f | [%.3f, %.3f] | %.3f | %.3f |" % (l, len(data[l]), sum(x) / len(x), lo, hi, sum(h) / len(h), hr))
    out += ["", "## Paired differences (A − B, same questions)", "",
            "| A | B | Δ acc | 95% CI | A-only | B-only | McNemar p |", "|---|---|---|---|---|---|---|"]
    for a, b in PAIRS:
        d = [x - y for x, y in zip(pooled[a], pooled[b])]
        lo, hi = ci(d)
        bo = sum(1 for x, y in zip(pooled[a], pooled[b]) if round(x) > round(y))
        co = sum(1 for x, y in zip(pooled[a], pooled[b]) if round(x) < round(y))
        out.append("| %s | %s | %+.3f | [%+.3f, %+.3f] | %d | %d | %.2g |" % (a, b, sum(d) / len(d), lo, hi, bo, co, mcnemar(bo, co)))
    pb = {i: next(iter(data["closed"][0][i] for _ in [0]))["pop_bucket"] for i in ids}
    out += ["", "## Accuracy by popularity bucket (n per bucket in header)", "",
            "| condition | " + " | ".join("%s (n=%d)" % (b, sum(1 for i in ids if pb[i] == b)) for b in BUCKETS) + " |",
            "|---|" + "---|" * len(BUCKETS)]
    for l, _, _ in CELLS:
        row = []
        for b in BUCKETS:
            v = [x for x, i in zip(pooled[l], ids) if pb[i] == b]
            row.append("%.3f" % (sum(v) / len(v)) if v else "-")
        out.append("| %s | %s |" % (l, " | ".join(row)))
    (HERE / "results" / "E0_TABLE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


main()
