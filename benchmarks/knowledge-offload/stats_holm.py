#!/usr/bin/env python3
"""Holm correction over the confirmatory family H1-H5, H7, from the p-values the E1 cells can give.

  python3 stats_holm.py                 # -> results/HOLM_TABLE.md

No model, no network. Raw p-values (all on the 1000-question E1 sample, `contains`, paired):
  H1a  `store` slope / `closed` slope < 1/2: one-sided bootstrap p = share of resamples (10k) with ratio >= 1/2.
  H1b  0.8B+store >= 27B closed: exact one-sided McNemar (sign test on discordant questions).
  H1   = max(H1a, H1b) (both parts must hold).
  H5a  forcing costs no accuracy: TOST equivalence at +-2 pts, bootstrap p = max of the two one-sided shares.
  H5b  forcing changes hallucination on `ablated`: exact two-sided McNemar on the hallucinated indicator.
A bootstrap p cannot go below 1/(B+1); it is printed as "< 1e-4". H2 (GSM8K), H3 (E2), H4 (E1b) and H7 (E7) have
no data yet and enter Holm as p = 1 (the conservative ranking: they sit last, and count in m).
How H5 is aggregated over sizes was not pre-registered; every size is shown and the choice is left to Opus.
"""
import sys
from fractions import Fraction
from math import comb
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import stats_e1 as E1                                                  # noqa: E402

FAMILY = ["H1", "H2", "H3", "H4", "H5", "H7"]
MARGIN = 0.02


def sign_p(a: int, b: int, two_sided: bool) -> float:
    """Exact sign-test p for a vs b discordant pairs (a = the direction of interest for one-sided)."""
    n = a + b
    if n == 0:
        return 1.0
    tail = Fraction(sum(comb(n, k) for k in range(0, min(a, b) + 1)), 2 ** n)
    if two_sided:
        return float(min(Fraction(1), 2 * tail))
    # one-sided: probability of >= a successes of n
    return float(Fraction(sum(comb(n, k) for k in range(a, n + 1)), 2 ** n))


def holm(ps: dict) -> dict:
    """Holm step-down adjusted p-values; `ps` name -> raw p."""
    order = sorted(ps, key=lambda k: ps[k])
    m, adj, run = len(order), {}, 0.0
    for i, k in enumerate(order):
        run = max(run, min(1.0, (m - i) * ps[k]))
        adj[k] = run
    return adj


def fmt(p, nb=E1.NB):
    return "<= %.0e (resolution)" % (1 / (nb + 1)) if p <= 1 / (nb + 1) + 1e-12 else "%.3g" % p


def build(results: Path):
    acc, lookup, bucket, abl = E1.load(results)
    ids = sorted(set.intersection(*(set(v) for v in acc.values())))
    n, nb = len(ids), E1.NB
    idx = E1.boot_idx(n, nb)
    out = ["# Holm over H1-H5, H7 (E1 data)", "", f"{n} questions, {nb} bootstrap resamples. Generated by `stats_holm.py`; see its docstring for each test.", ""]
    rows, raw = [], {}

    # H1a, per quant
    for q in E1.QUANTS:
        ss = [s for s in E1.SIZES if all((s, q, c) in acc for c in ("closed", "store"))]
        xs = np.log10([E1.PARAMS[s] for s in ss])
        bt = {}
        for c in ("closed", "store"):
            m = E1.mat(acc, [(s, q, c) for s in ss], ids)
            bt[c] = E1.slope(np.stack([m[:, idx[b]].mean(axis=1) for b in range(nb)]), xs)
        ratio = bt["store"] / bt["closed"]
        p = float((np.sum(ratio >= 0.5) + 1) / (nb + 1))
        rows.append(("H1a", q, "-", "store/closed slope ratio < 0.5", "%.2f" % np.median(ratio), p))
        raw[("H1a", q)] = p
    # H1b
    for q in E1.QUANTS:
        a, b = (("0.8b", q, "store"), ("27b", q, "closed"))
        if a in acc and b in acc:
            ao = sum(1 for i in ids if acc[a][i] > acc[b][i])
            bo = sum(1 for i in ids if acc[a][i] < acc[b][i])
            rows.append(("H1b", q, "0.8b vs 27b", "0.8B store > 27B closed (%d vs %d discordant)" % (ao, bo), "-", sign_p(ao, bo, False)))
            raw[("H1b", q)] = sign_p(ao, bo, False)
    # H5a TOST
    TOOL, TC = "tool/search_first", "tool+contract/search_first"
    for q in E1.QUANTS:
        for s in E1.SIZES:
            if (s, q, TC) in acc and (s, q, TOOL) in acc:
                d = np.array([acc[(s, q, TC)][i] - acc[(s, q, TOOL)][i] for i in ids], dtype=float)
                bd = d[idx].mean(axis=1)
                p = float(max((np.sum(bd <= -MARGIN) + 1) / (nb + 1), (np.sum(bd >= MARGIN) + 1) / (nb + 1)))
                rows.append(("H5a", q, s, "contract - tool within +-%.2f (diff %+.3f)" % (MARGIN, d.mean()), "%+.3f" % d.mean(), p))
                raw[("H5a", q, s)] = p
    # H5b
    for q in E1.QUANTS:
        for s in E1.SIZES:
            ka, kb = (s, q, "tool+contract/abstain_ok"), (s, q, "tool/abstain_ok")
            if ka in abl and kb in abl:
                ha = np.array([a["outcome"] == "hallucinated" for a in abl[ka]])
                hb = np.array([a["outcome"] == "hallucinated" for a in abl[kb]])
                ao, bo = int((ha & ~hb).sum()), int((~ha & hb).sum())
                p = sign_p(ao, bo, True)
                rows.append(("H5b", q, s, "hallucination contract vs tool (%d vs %d discordant of 200)" % (ao, bo), "%+.3f" % (ha.mean() - hb.mean()), p))
                raw[("H5b", q, s)] = p
    out += ["## Raw p-values", "", "| test | quant | size | what | estimate | raw p |", "|---|---|---|---|---|---|"]
    out += ["| %s | %s | %s | %s | %s | %s |" % (t, q, s, w, e, ("%.2g" % p) if t in ("H1b", "H5b") else fmt(p)) for t, q, s, w, e, p in rows]

    # Holm scenarios: H1 = max(H1a, H1b); H5 = the size choice shown (9B, 27B, 4B, 2B) for each quant
    out += ["", "## Holm (family H1, H2, H3, H4, H5, H7; m = 6; H2, H3, H4, H7 have no data, p = 1)", "",
            "H1 is IQ4_XS or Q8_0 as shown. H5 is shown per size and per sub-test, because the size aggregation was not pre-registered "
            "(a flag for Opus); the family always contains exactly one H5 entry.", "",
            "| H1 on | H5 test | H5 on | H1 raw | H1 Holm | H5 raw | H5 Holm |", "|---|---|---|---|---|---|---|"]
    for q in E1.QUANTS:
        h1 = max(raw[("H1a", q)], raw.get(("H1b", q), 1.0))
        for t in ("H5a", "H5b"):
            for s in E1.SIZES:
                if (t, q, s) not in raw:
                    continue
                fam = {"H1": h1, "H2": 1.0, "H3": 1.0, "H4": 1.0, "H5": raw[(t, q, s)], "H7": 1.0}
                adj = holm(fam)
                out.append("| %s | %s | %s %s | %s | %s | %s | %s |" % (q, t, q, s, fmt(h1), fmt(adj["H1"]), fmt(raw[(t, q, s)]), fmt(adj["H5"])))
    out += ["", "Equivalence (H5a) is declared when the TOST p is below the Holm threshold; a p of 1 or near it means equivalence "
            "was not shown at that size (at 0.8B and 2B IQ4_XS the tool is skipped or degraded, see E1_TABLE.md).",
            "H1 on Q8_0 is 1 because H1b cannot be tested there (no 27B Q8_0 cell; its size on disk was not measured by me). H5a at 0.8B is a vacuous equivalence: the model never calls the tool (lookup rate <= .011), so both arms are `closed`-like.",
            "H5b with no discordant questions (p = 1) is not a test: the two arms gave identical outcomes.", "",
            "**p-values still missing:** H2 (GSM8K arm not run), H3 (E2 not run), H4 (E1b not run), H7 (E7 not run). "
            "H5(c) is descriptive and has no p. H6 and H8 are outside the family."]
    out += default_prompt_section(results, raw)
    return out


def h5_default_entry(h5a_p, h5b_p) -> float:
    """D14: the family's one H5 p is max(pooled H5a TOST p, pooled H5b MH p); an untestable H5a counts as 1."""
    return max(1.0 if h5a_p is None else h5a_p, h5b_p)


def default_prompt_section(results: Path, raw: dict) -> list:
    """H5 as pre-registered by D12/D14 (default prompt, 36 cells, stats_h5h8.py) in the Holm step; the rows above are the
    E1 `search_first` arm and are kept as the earlier, superseded form."""
    import stats_h5h8 as H58
    res = H58.analyse(results)
    out = ["", "## Holm with H5 as pre-registered (D12/D14: default-prompt cells, `stats_h5h8.py`)", "",
           "The H5 rows above come from the `search_first` arm (the E1 form, superseded by D12). Here H5 = max(pooled H5a TOST p over eligible "
           "sizes, pooled H5b matched-pairs MH p) per quant; H5a with no eligible size counts as p = 1. H2, H3, H4, H7 have no data (p = 1). "
           "H1 is the E1 value for that quant. The pooled H5b treats sizes as independent strata although the 200 questions repeat (optimistic).", "",
           "| quant | H1 raw | H5a pooled p | H5b pooled p (exact) | H5 raw | H1 Holm | H5 Holm | H5 survives Holm at .05 |",
           "|---|---|---|---|---|---|---|---|"]
    for q in E1.QUANTS:
        h1 = max(raw[("H1a", q)], raw.get(("H1b", q), 1.0))
        a = res["h5a_pooled"].get(q, {}).get("p")
        b = res["h5b_pooled"][q]["p_exact"]
        h5 = h5_default_entry(a, b)
        adj = holm({"H1": h1, "H2": 1.0, "H3": 1.0, "H4": 1.0, "H5": h5, "H7": 1.0})
        out.append("| %s | %s | %s | %.3g | %s | %s | %s | %s |" % (
            q, fmt(h1), "not testable (no eligible size)" if a is None else fmt(a), b, fmt(h5), fmt(adj["H1"]), fmt(adj["H5"]),
            "yes" if adj["H5"] < 0.05 else "no"))
    out += ["", "Tests with data now: H1 (E1; IQ4_XS complete, Q8_0 lacks 27B) and H5 (a, b). Still without data: H2 (GSM8K), H3 (E2), H4 (E1b), H7 (E7)."]
    return out


def main():
    results = HERE / "results"
    out = build(results)
    (results / "HOLM_TABLE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
