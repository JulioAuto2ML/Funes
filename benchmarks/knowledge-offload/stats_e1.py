#!/usr/bin/env python3
"""E1 table: accuracy over model size and condition, paired differences, H1 slopes, buckets, ablated arm.

  python3 stats_e1.py                      # -> results/E1_TABLE.md

No model, no network. Reads the result files under results/ by what is inside them (`model_tag`,
`condition`, `prompt_variant`, `arm`), reusing stats_e0's cell finder. Sizes are Qwen3.5 0.8/2/4/9/27B;
the main curve is IQ4_XS, the control curve Q8_0 (no 27B). Primary metric `contains`, on the sample
(1000 stratified unambiguous items, the same questions at every size). CIs are percentile bootstraps over
questions (2000 resamples); a resample draws one set of questions and applies it to every size and
condition, so differences and slopes are paired. H1's slope is accuracy against log10(parameters in B).
"""
import argparse
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import stats_e0 as S0                                                   # noqa: E402
from ko import models as M                                              # noqa: E402

PREFIX = "popqa-stratified1u"
SIZES = ["0.8b", "2b", "4b", "9b", "27b"]
PARAMS = {"0.8b": 0.8, "2b": 2.0, "4b": 4.0, "9b": 9.0, "27b": 27.0}
QUANTS = ["iq4_xs", "q8_0"]
CONDS = ["closed", "oracle", "store", "tool/search_first", "tool+contract/search_first", "web/search_first",
         "web+writeback/search_first"]
NB = 10000


def tag(size, quant):
    return f"qwen3.5-{size}-{quant}"


def load(results: Path):
    """(size, quant, label) -> {id: contains}; plus bucket map, lookup rate, ablated cells."""
    acc, lookup, bucket, abl = {}, {}, {}, {}
    for q in QUANTS:
        for s in SIZES:
            t = tag(s, q)
            for lab, reps in S0.find_cells(results, PREFIX, t).items():
                for p in S0.passes(lab):
                    name = lab if len(S0.passes(lab)) == 1 else f"{lab} p{p}"
                    rows = [a for a in reps[0]["answers"] if a["pass"] == p]
                    acc[(s, q, name)] = {a["id"]: int(a["contains"]) for a in rows}
                    lookup[(s, q, name)] = float(np.mean([bool(a["tools"]) for a in rows]))
                    for a in rows:
                        bucket[a["id"]] = a["pop_bucket"]
            for lab, reps in S0.find_ablated(results, PREFIX, t).items():
                abl[(s, q, lab)] = [a for a in reps[0]["answers"] if a["pass"] == 1]
    return acc, lookup, bucket, abl


def mat(acc, keys, ids):
    return np.array([[acc[k][i] for i in ids] for k in keys], dtype=float)


def boot_idx(n, nb=NB, seed=0):
    return np.random.default_rng(seed).integers(0, n, size=(nb, n))


def pct(x):
    return float(np.percentile(x, 2.5)), float(np.percentile(x, 97.5))


def slope(accs, x):
    """OLS slope of accs (last axis = sizes) on x; works on a (nb, k) matrix."""
    xc = x - x.mean()
    return (accs - accs.mean(axis=-1, keepdims=True)) @ xc / (xc @ xc)


def regex_check(results: Path) -> str:
    """The abstain regex against julio's hand labels, measured from the tsv (nothing quoted from a report)."""
    import csv
    import label_abstain as LA
    tsv = results / "abstain_labels.tsv"
    if not tsv.exists():
        return "The abstain regex is NOT validated (no `results/abstain_labels.tsv`): `abstained` vs `hallucinated` is provisional."
    with open(tsv, encoding="utf-8", newline="") as f:
        r = LA.agreement(list(csv.DictReader(f, delimiter="\t")))
    if not r["labelled"]:
        return "The abstain regex is NOT validated (`human` column empty): `abstained` vs `hallucinated` is provisional."
    dis = "; ".join(f"{d['condition']} #{d['id']} {d['prediction']!r} regex={d['regex']} human={d['human']}" for d in r["disagreements"])
    return (f"Abstain regex vs hand labels (`python3 label_abstain.py score results/abstain_labels.tsv`): "
            f"{r['agree']}/{r['labelled']} agree ({r['rate']:.1%}; a sample of 50 answers, half the regex called abstained, half not)"
            + (f"; disagreement: {dis}." if dis else "."))


def build(results: Path):
    acc, lookup, bucket, abl = load(results)
    lock = M.load_lock()
    ids = sorted(set.intersection(*(set(v) for v in acc.values())))
    n = len(ids)
    idx = boot_idx(n)
    out = [f"# E1 results — Qwen3.5 0.8 / 2 / 4 / 9 / 27B, cell set `{PREFIX}`", "",
           f"Questions: {n} (same at every size and condition; stratified by popularity, unambiguous items, dataset seed 1). "
           "Metric `contains`; 1 repeat (greedy, bit-identical across repeats). 95% CIs: percentile bootstrap over questions, "
           f"{NB} resamples, one resample shared by all sizes and conditions so every difference and slope is paired. "
           "Generated by `stats_e1.py`.", ""]
    sizes_have = lambda q, c: [s for s in SIZES if (s, q, c) in acc]

    def cell_ci(key):
        v = np.array([acc[key][i] for i in ids], dtype=float)
        lo, hi = pct(v[idx].mean(axis=1))
        return v.mean(), lo, hi

    def diff_ci(ka, kb):
        d = np.array([acc[ka][i] - acc[kb][i] for i in ids], dtype=float)
        lo, hi = pct(d[idx].mean(axis=1))
        ao, bo = int((d > 0).sum()), int((d < 0).sum())
        return d.mean(), lo, hi, ao, bo, S0.mcnemar(ao, bo)

    # ---- accuracy
    for q, title in (("iq4_xs", "Main curve: IQ4_XS"), ("q8_0", "Control curve: Q8_0")):
        out += [f"## Accuracy — {title}", "", "| condition | " + " | ".join(SIZES) + " |",
                "|---|" + "---|" * len(SIZES)]
        for c in CONDS:
            if not sizes_have(q, c):
                continue
            row = []
            for s in SIZES:
                if (s, q, c) in acc:
                    m, lo, hi = cell_ci((s, q, c))
                    row.append("%.3f [%.3f, %.3f]" % (m, lo, hi))
                else:
                    row.append("–")
            out.append(f"| {c} | " + " | ".join(row) + " |")
        out.append("")
    out += ["**The 27B `web` cell is not valid:** from question 446 of 1000 on, every Parallel search returned a 402 'Insufficient credit' error "
            "(1661 of 2086 searches, 527 of 951 searched questions; measured in `results/WEB_AUDIT.md`), so its .525 mixes the model with an exhausted account. "
            "`web` was run at 0.8B, 9B and 27B (IQ4_XS) only; `web+writeback` at 9B only (pass 1 / pass 2 shown as `p1`/`p2`).", ""]

    # ---- lookup propensity
    out += ["## Lookup rate (share of answers with at least one tool call; prompt `search_first`)", "",
            "| condition | quant | " + " | ".join(SIZES) + " |", "|---|---|" + "---|" * len(SIZES)]
    for c in ("tool/search_first", "tool+contract/search_first", "web/search_first"):
        for q in QUANTS:
            if sizes_have(q, c):
                out.append(f"| {c} | {q} | " + " | ".join(
                    "%.3f" % lookup[(s, q, c)] if (s, q, c) in lookup else "–" for s in SIZES) + " |")
    out += ["", "H8 as written (lookup under the *default* prompt vs size) was not run: E1 used `search_first` for every tool cell, "
            "so this table is lookup propensity under that prompt, not H8.", ""]

    # ---- paired differences
    def diff_table(title, pairs, quants=("iq4_xs",)):
        rows = []
        for q in quants:
            for a, b in pairs:
                for s in SIZES:
                    ka, kb = (s, q, a), (s, q, b)
                    if ka in acc and kb in acc:
                        d, lo, hi, ao, bo, p = diff_ci(ka, kb)
                        rows.append("| %s | %s | %s | %s | %+.3f | [%+.3f, %+.3f] | %d | %d | %.2g |" % (
                            q, s, a, b, d, lo, hi, ao, bo, p))
        return [f"## {title}", "", "| quant | size | A | B | Δ (A−B) | 95% CI | A-only | B-only | McNemar p |",
                "|---|---|---|---|---|---|---|---|---|"] + rows + [""]

    TOOL, TC, WEB = "tool/search_first", "tool+contract/search_first", "web/search_first"
    out += diff_table("Paired differences — store and tools vs closed", [("store", "closed"), ("oracle", "store"),
                                                                          (TOOL, "store"), (TC, "store"), (TC, TOOL)],
                      quants=("iq4_xs", "q8_0"))
    out += diff_table("Paired differences — web vs store, tool, closed", [(WEB, "store"), (WEB, TOOL), (WEB, "closed")])
    out += diff_table("Paired differences — web+writeback vs plain web (9B)",
                      [("web+writeback/search_first p1", WEB), ("web+writeback/search_first p2", WEB),
                       ("web+writeback/search_first p2", "web+writeback/search_first p1")])

    # ---- quant effect
    rows = []
    for c in CONDS:
        for s in SIZES:
            ka, kb = (s, "q8_0", c), (s, "iq4_xs", c)
            if ka in acc and kb in acc:
                d, lo, hi, ao, bo, p = diff_ci(ka, kb)
                rows.append("| %s | %s | %.3f | %.3f | %+.3f | [%+.3f, %+.3f] | %d | %d | %.2g |" % (
                    s, c, acc[kb] and np.mean(list(acc[kb].values())), np.mean(list(acc[ka].values())), d, lo, hi, ao, bo, p))
    out += ["## Quantisation control: Q8_0 − IQ4_XS (same model, same questions)", "",
            "| size | condition | IQ4_XS | Q8_0 | Δ | 95% CI | Q8-only | IQ4-only | McNemar p |",
            "|---|---|---|---|---|---|---|---|---|"] + rows + [""]

    # ---- H1
    out += ["## H1 — slope of accuracy against log10(parameters in B)", "",
            "Sizes 0.8, 2, 4, 9, 27 (nominal parameters from `models.lock`: " +
            ", ".join(f"{s} = {lock[tag(s, 'iq4_xs')]['params_b'] if tag(s, 'iq4_xs') in lock else PARAMS[s]}" for s in SIZES) +
            "). Slope = OLS accuracy points per decade of parameters. H1 criteria (pre-registered): `store` slope < ½ the `closed` slope, "
            "and the 0.8B `store` ≥ the 27B `closed`.", ""]
    x = np.log10([PARAMS[s] for s in SIZES])
    out += ["| quant | condition | slope (acc / decade) | 95% CI | ratio to `closed` | 95% CI of ratio | ratio upper CI < 0.5 |",
            "|---|---|---|---|---|---|---|"]
    h1 = {}
    for q in QUANTS:
        ss = [s for s in SIZES if all((s, q, c) in acc for c in ("closed", "store"))]
        if len(ss) < 3:
            continue
        xs = np.log10([PARAMS[s] for s in ss])
        boots = {}
        for c in ("closed", "store", "oracle", TOOL, TC):
            if all((s, q, c) in acc for s in ss):
                m = mat(acc, [(s, q, c) for s in ss], ids)           # (sizes, n)
                accs = np.stack([m[:, idx[b]].mean(axis=1) for b in range(NB)])   # (NB, sizes)
                boots[c] = (slope(m.mean(axis=1), xs), slope(accs, xs))
        cl_pt, cl_b = boots["closed"]
        for c, (pt, bt) in boots.items():
            lo, hi = pct(bt)
            if c == "closed":
                out.append("| %s | %s | %+.3f | [%+.3f, %+.3f] | 1 | – | – |" % (q, c, pt, lo, hi))
                continue
            r_pt, r_b = pt / cl_pt, bt / cl_b
            rlo, rhi = pct(r_b)
            out.append("| %s | %s | %+.3f | [%+.3f, %+.3f] | %.2f | [%.2f, %.2f] | %s |" % (
                q, c, pt, lo, hi, r_pt, rlo, rhi, "yes" if rhi < 0.5 else "no"))
            h1[(q, c)] = (r_pt, rlo, rhi)
    out.append("")
    # smallest + store vs largest closed (IQ4 main; paired over questions)
    a, b = ("0.8b", "iq4_xs", "store"), ("27b", "iq4_xs", "closed")
    d, lo, hi, ao, bo, p = diff_ci(a, b)
    out += ["**0.8B + `store` vs 27B `closed`** (IQ4_XS): %.3f vs %.3f, Δ = %+.3f [%+.3f, %+.3f] (%d vs %d discordant, McNemar p = %.2g)." % (
        np.mean(list(acc[a].values())), np.mean(list(acc[b].values())), d, lo, hi, ao, bo, p), ""]
    out += ["Read the `tool` rows with care: their slope is not a knowledge slope. At 0.8B (IQ4_XS and Q8_0) the model almost never calls "
            "the tool and at 2B IQ4_XS it skips it on ~20% of questions (lookup-rate table), so the line measures how well each size "
            "drives the tool, and `tool` climbs steeply from a floor. The knowledge-supply claim rests on `store` and `oracle`, "
            "where the facts are injected without the model's choice. `oracle` − `store` shrinks with size (0.8B +.051, 27B +.006), "
            "i.e. the part of the `store` slope that is retrieval-then-reading, not knowledge.", "",
            "Per-size gap (IQ4_XS):", ""]
    q = "iq4_xs"
    ss = [s for s in SIZES if all((s, q, c) in acc for c in ("closed", "store"))]
    out += ["| size | closed | store | store − closed |", "|---|---|---|---|"]
    for s in ss:
        d, lo, hi, *_ = diff_ci((s, q, "store"), (s, q, "closed"))
        out.append("| %s | %.3f | %.3f | %+.3f [%+.3f, %+.3f] |" % (
            s, np.mean(list(acc[(s, q, "closed")].values())), np.mean(list(acc[(s, q, "store")].values())), d, lo, hi))
    out.append("")

    # ---- buckets
    bk = sorted(set(bucket[i] for i in ids), key=lambda s: int(s[2:]))
    for q in QUANTS:
        out += [f"## Accuracy by popularity bucket — {q}", "",
                "| size | condition | " + " | ".join("%s (n=%d)" % (b, sum(1 for i in ids if bucket[i] == b)) for b in bk) + " |",
                "|---|---|" + "---|" * len(bk)]
        for s in SIZES:
            for c in ("closed", "store", TC, WEB):
                if (s, q, c) in acc:
                    out.append(f"| {s} | {c} | " + " | ".join(
                        "%.3f" % np.mean([acc[(s, q, c)][i] for i in ids if bucket[i] == b]) for b in bk) + " |")
        out.append("")
    out += ["Buckets 1e0, 1e6 and 1e7 hold 16, 8 and 2 questions: read nothing into them.", ""]

    # ---- ablated
    out += ["## Ablated arm (own triple withheld from retrieval, prompt `abstain_ok`, first 200 questions)", "",
            "Outcome: correct (answered from weights) / abstained (regex `ko/ablate.py`) / hallucinated (a wrong answer). " +
            regex_check(results) + " CI is on the hallucinated share.", "",
            "| quant | size | condition | n | correct | abstained | hallucinated | 95% CI halluc. | lookup rate |",
            "|---|---|---|---|---|---|---|---|---|"]
    abl_order = ["closed", "store", "tool/abstain_ok", "tool+contract/abstain_ok"]
    def abl_name(lab):
        return lab
    abl_idx = boot_idx(200, seed=1)
    abl_h = {}
    for q in QUANTS:
        for s in SIZES:
            for lab in sorted([k[2] for k in abl if k[0] == s and k[1] == q], key=lambda l: S0.sort_key(l)):
                rows = abl[(s, q, lab)]
                m = len(rows)
                oc = np.array([a["outcome"] for a in rows])
                hal = (oc == "hallucinated").astype(float)
                abl_h[(s, q, lab)] = hal
                lo, hi = pct(hal[boot_idx(m, seed=1)].mean(axis=1))
                out.append("| %s | %s | %s | %d | %.3f | %.3f | %.3f | [%.3f, %.3f] | %.2f |" % (
                    q, s, lab, m, (oc == "correct").mean(), (oc == "abstained").mean(), hal.mean(), lo, hi,
                    np.mean([bool(a["tools"]) for a in rows])))
    out.append("")
    out += ["### Ablated: paired differences in hallucination rate (A − B)", "",
            "| quant | size | A | B | Δ halluc. | 95% CI |", "|---|---|---|---|---|---|"]
    for q in QUANTS:
        for s in SIZES:
            labs = sorted(k[2] for k in abl_h if k[0] == s and k[1] == q)
            ref = lambda base: next((l for l in labs if l.split("/")[0] == base), None)
            for a_, b_ in (("store", "closed"), ("tool+contract", "tool"), ("tool+contract", "store"), ("tool", "store")):
                la, lb = ref(a_), ref(b_)
                if la and lb:
                    d = abl_h[(s, q, la)] - abl_h[(s, q, lb)]
                    lo, hi = pct(d[boot_idx(len(d), seed=1)].mean(axis=1))
                    out.append("| %s | %s | %s | %s | %+.3f | [%+.3f, %+.3f] |" % (q, s, la, lb, d.mean(), lo, hi))
    out.append("")
    return out, acc, h1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default=str(HERE / "results"))
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    results = Path(a.results)
    out, _, _ = build(results)
    dest = Path(a.out) if a.out else results / "E1_TABLE.md"
    dest.write_text("\n".join(out) + "\n")
    print("\n".join(out))
    print(f"\n-> {dest}", file=sys.stderr)


if __name__ == "__main__":
    main()
